const DEFAULT_CATEGORY = "general"

const UNSPLASH_BASE = "https://images.unsplash.com/photo-"
const UNSPLASH_PARAMS = "?w=1200&q=85&fit=crop&auto=format"

function hashString(str: string): number {
  let hash = 5381
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash + str.charCodeAt(i)) & 0xffffffff
  }
  return Math.abs(hash)
}

export function getCuratedImageUrl(categorySlug?: string, seed?: string): string {
  const cat = categorySlug?.toLowerCase() || DEFAULT_CATEGORY
  const pool = UNSPLASH_PHOTOS[cat]
  if (!pool || pool.length === 0) {
    const defaultPool = UNSPLASH_PHOTOS[DEFAULT_CATEGORY]
    const idx = seed ? hashString(seed) % defaultPool.length : Math.floor(Math.random() * defaultPool.length)
    return UNSPLASH_BASE + defaultPool[idx] + UNSPLASH_PARAMS
  }
  const idx = seed ? hashString(seed) % pool.length : Math.floor(Math.random() * pool.length)
  return UNSPLASH_BASE + pool[idx] + UNSPLASH_PARAMS
}

export function getCuratedImageUrlWithRotation(categorySlug?: string, dateStr?: string): string {
  const cat = categorySlug?.toLowerCase() || DEFAULT_CATEGORY
  const pool = UNSPLASH_PHOTOS[cat]
  if (!pool || pool.length === 0) {
    const defaultPool = UNSPLASH_PHOTOS[DEFAULT_CATEGORY]
    const rotationSeed = (dateStr || String(new Date().getTime())) + cat
    const idx = hashString(rotationSeed) % defaultPool.length
    return UNSPLASH_BASE + defaultPool[idx] + UNSPLASH_PARAMS
  }
  const rotationSeed = (dateStr || String(new Date().getTime())) + cat
  const idx = hashString(rotationSeed) % pool.length
  return UNSPLASH_BASE + pool[idx] + UNSPLASH_PARAMS
}
